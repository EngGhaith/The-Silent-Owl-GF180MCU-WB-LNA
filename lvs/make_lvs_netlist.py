#!/usr/bin/env python3
"""xschem netlist of xschem/lna_core_parts.sch (coils from the "lvsrm" .lib sections) -> netgen reference for the
Magic/Netgen run_full_lvs flow (device names as Magic extracts them with extra_be_checks/tech/gf180mcuD).
usage: make_lvs_netlist.py raw.spice out.spice [--nfet05=nfet_06v0]
  - nfet_05v0 -> nfet_06v0 (the Magic tech ignores the 5V marker 112/1 and extracts every thick-oxide nFET as 06v0)
  - cap_mim_2f0fF -> cap_mim_2f0_m4m5_noshield, W/L snapped to the 10 nm drawing grid
  - rm1..rm4 / tm11k from the lvsrm sections -> subcircuit calls with r_width / r_length
  - ideal L and ideal (loss) R removed"""
import re, sys

raw, out = sys.argv[1], sys.argv[2]
NFET05 = "nfet_06v0"
for a in sys.argv[3:]:
    if a.startswith("--nfet05="):
        NFET05 = a.split("=", 1)[1]

def um(v):
    """'49.8865e-6' / '7u' / '1e-06' -> value in um, snapped to 10 nm (drawing grid)"""
    v = v.strip("'")
    f = float(v[:-1]) if v.endswith("u") else float(v) * 1e6
    return f"{round(f, 2):g}u"

def lib_section(path, sec):
    body, on = [], False
    for ln in open(path):
        s = ln.strip()
        if s.lower().startswith(".lib ") and s.split()[1] == sec:
            on = True; continue
        if s.lower().startswith(".endl"):
            on = False; continue
        if on and s and not s.startswith("*"):
            body.append(s)
    return body

# join continuation lines
lines = []
for ln in open(raw):
    ln = ln.rstrip("\n")
    if ln.startswith("+") and lines:
        lines[-1] += " " + ln[1:]
    else:
        lines.append(ln)

res = []
top_pins = None
for ln in lines:
    s = ln.strip()
    if s.startswith("**.subckt"):
        top_pins = s.split()[2:]
        continue
    if s.startswith("*+") and top_pins is not None and not res:
        top_pins += s[2:].split(); continue
    if s.lower().startswith(".lib "):
        _, path, sec = s.split()
        res.extend(lib_section(path, sec)); continue
    if not s or s.startswith("*") or s.lower() in (".end",):
        continue
    res.append(s)

def conv(s):
    tok = s.split()
    if not tok or tok[0].startswith("."):
        if tok and tok[0].lower() in (".subckt", ".ends"):
            return " ".join([tok[0].lower()] + [t.lower() if i == 0 else t for i, t in enumerate(tok[1:])])
        return s
    name = tok[0]
    # metal resistors from the lvsrm sections: R1 p1 p2 rm4 W=6u L=1u
    if name[0] in "Rr" and len(tok) >= 4 and re.match(r"^(rm[1-4]|tm11k)$", tok[3]):
        p = dict(t.split("=", 1) for t in tok[4:] if "=" in t)
        return f"X{name} {tok[1]} {tok[2]} {tok[3]} r_width={um(p['W'])} r_length={um(p['L'])}"
    if name[0] in "Rr" and len(tok) == 4:            # ideal (loss) R
        return None
    if name[0] in "Ll" and len(tok) == 4:            # ideal L
        return None
    if name[0] in "Xx":
        # strip spice expressions left from pdk symbols (ad/as/... with quotes)
        tok = [t for t in tok if not re.match(r"^(ad|as|pd|ps|nrd|nrs|sa|sb|sd)=", t) and "'" not in t
               and t not in ("*", "/", "W", "W/nf", "0.18u", "(W/nf", "+", "0.18u)")]
        model_i = next((i for i, t in enumerate(tok[1:], 1) if "=" in t), len(tok)) - 1
        model = tok[model_i]
        if model == "nfet_05v0":
            tok[model_i] = NFET05
        if model == "cap_mim_2f0fF":
            tok[model_i] = "cap_mim_2f0_m4m5_noshield"
            tok = [f"{t.split('=')[0]}={um(t.split('=')[1])}" if t.split("=")[0] in ("c_width", "c_length") else t
                   for t in tok]
        tok[model_i] = tok[model_i].lower()
        if model in ("rm1", "rm2", "rm3", "rm4", "tm11k", "ppolyf_u_1k", "ppolyf_u_1k_6p0"):
            tok = [f"{t.split('=')[0]}={um(t.split('=')[1])}" if t.split("=")[0] in ("r_width", "r_length") else t
                   for t in tok]
        return " ".join(tok)
    return s

body = [c for c in (conv(s) for s in res) if c]
with open(out, "w") as f:
    f.write("* netgen reference for lna_core_parts (generated by mkref.py from the xschem netlist)\n")
    f.write(".subckt lna_core_parts " + " ".join(top_pins) + "\n")
    # top-level instances come before the first .subckt in the xschem netlist
    i = 0
    while i < len(body) and not body[i].startswith(".subckt"):
        f.write(body[i] + "\n"); i += 1
    f.write(".ends\n")
    for b in body[i:]:
        f.write(b + "\n")
print("wrote", out)
