#!/usr/bin/env python3
"""
Real PDK geometry for the lna_core floorplan: every FET row, poly resistor and MIM of xschem/lna_core.sch
is generated with the gf180mcu KLayout PCells and written as static cells.

Run with KLayout (the PCells need its python):   klayout -b -r make_lna_core_devices.py

Writes
  lna_core_devices.gds    one cell per device (PCells flattened), origin as generated by the PCell
  lna_core_devices.json   {cell: {"bbox": [x0, y0, x1, y1] um, "params": {...}, "info": "..."}}

Sizes come from lna_core.sch (read only). FETs are drawn as rows: units x nf active fingers plus the dummy
fingers of the matching *D device (e.g. M2D) at both row ends, as one PCell row with shared diffusion.
"""
import json, math, os, re, sys

import pya

HERE = os.path.dirname(os.path.abspath(__file__))
SCH = os.path.join(HERE, "..", "..", "xschem", "lna_core.sch")
sys.path.insert(0, "/foss/pdks/gf180mcuD/libs.tech/klayout/tech/pymacros")
import cells  # noqa: E402  (gf180mcu PCell library)

ROWS = {"M2": 2, "M4": 1, "M1": 1}  # rows per FET array; units per row = m / rows
VOLT = {"nfet_03v3": "3.3V", "nfet_05v0": "5V", "nfet_06v0": "6V"}

# MIM tile = PCell (top plate W x L on Metal5/FuseTop, bottom plate Metal4 with 0.6 um enclosure) + what it needs to
# be connected, after mim_b.drc (MIM option B, Metal4/Metal5, Via4):
#   bottom plate only contactable from above via Via4 (MIMTM.10) -> Metal4 tab on the west side with 2 Via4 columns
#   (Via4 0.26, space 0.36) and a Metal5 strap; Via4 >= 0.4 in Metal4 (MIMTM.2) and >= 0.4 from the top plate
#   (MIMTM.5); strap >= 0.6 from the top plate Metal5 (MT.2b, wide metal)
#   Metal5 leads LEAD_W wide: bottom plate -> west, top plate -> east, LEAD_LEN past the halo
#   halo: 1.2 um around the bottom plate (MIMTM.1, bottom plate to any Metal4)
M4, V4, M5, FP = (46, 0), (41, 0), (81, 0), (255, 15)
MIM_ENC, MIM_HALO, LEAD_W, LEAD_LEN = 0.6, 1.2, 6.0, 3.0
TAB_STRAP = (-3.0, -1.0)  # x range of the Metal5 strap on the tab (top plate starts at x = 0)
TAB_VIA_X = (-2.53, -1.73)  # left edges of the 2 Via4 columns
TAB_M4 = -3.4  # west edge of the Metal4 tab
VIA, VIA_PITCH = 0.26, 0.62

# FET tile = PCell row (gate contacts all on top) + what it needs to be wired, sized for the DC current:
#   gate bus Metal1 GATE_W above the row (>= 0.3 um from the PCell Metal1)
#   drain bus Metal2 over the row (Via1 straight down onto the drain fingers), widened upwards for the current
#   source bus Metal2 below the row, BUS_GAP from the row
#   buses run BUS_EXT past both row ends (taps), FET_HALO all around
# bus width = row current / J_EM. Drain currents: ngspice OP of lna-core_tb.sch (typ, 2026-10-15).
# J_EM = 1 mA/um is a design value for Metal1/Metal2 (assumption, not taken from the PDK docs).
ID_MA = {"M2": 8.75, "M1": 13.2, "M4": 13.2}
J_EM = 1.0  # mA/um
M1L, M2L = (34, 0), (36, 0)
GATE_W, GATE_GAP, BUS_GAP, BUS_EXT, FET_HALO, BUS_MIN = 1.0, 0.3, 0.5, 2.0, 1.0, 2.0

# Supply fill tiles (20 x 20 um, origin in the centre), from upstream/main_pex klayout/ (2026-10-14), copied unchanged
# to cells/: M5 = VDD, M4 = VSS, M3 = VDD, M2 = VSS, M1 = VSS, SUB tap = VSS; the dcpl_mim version adds 4 MIMs
# (top plate M5 = VDD, bottom plate M4 = VSS). Cells are imported with a prefix (both files use via_dev, ...).
PG_TILES = {"PG_PLAIN": "vss_m1m2m4_vdd_m3m5_20x20.gds", "PG_MIM": "vss_m1m2m4_vdd_m3m5_dcpl_mim_20x20.gds"}


def um(v):
    v = v.strip()
    return float(v[:-1]) if v.endswith("u") else float(v) * 1e6


def sch_devices(path=SCH):
    """[(symbol, {param: value})] of every instance in the schematic"""
    out = []
    for sym, body in re.findall(r"^C \{([^}]*)\}[^{]*\{(.*?)\}", open(path).read(), re.S | re.M):
        out.append((os.path.basename(sym)[:-4], dict(re.findall(r"(\w+)=(\S+)", body))))
    return out


def fet_tile(ly, c, i_row):
    """add gate / drain / source buses + footprint marker around the flat FET row in c"""
    b = c.dbbox()
    box = lambda layer, x0, y0, x1, y1: c.shapes(ly.layer(*layer)).insert(pya.DBox(x0, y0, x1, y1))
    wbus = max(BUS_MIN, math.ceil(i_row / J_EM * 2) / 2)  # 0.5 um steps
    x0, x1 = b.left - BUS_EXT, b.right + BUS_EXT
    gate = (x0, b.top + GATE_GAP, x1, b.top + GATE_GAP + GATE_W)
    drain = (x0, b.bottom + 0.3, x1, max(b.bottom + 0.3 + wbus, b.top))
    source = (x0, b.bottom - BUS_GAP - wbus, x1, b.bottom - BUS_GAP)
    box(M1L, *gate)
    box(M2L, *drain)
    box(M2L, *source)
    fp = (x0 - FET_HALO, source[1] - FET_HALO, x1 + FET_HALO, max(gate[3], drain[3]) + FET_HALO)
    box(FP, *fp)
    r3 = lambda v: [round(x, 3) for x in v]
    return {"bbox": r3(fp), "row": r3((b.left, b.bottom, b.right, b.top)),
            "buses": {"gate": r3(gate), "drain": r3(drain), "source": r3(source)}, "bus_w": wbus, "i_row_mA": i_row}


def import_tile(ly, name, fname):
    """copy the TOP cell of cells/<fname> (with its sub cells, renamed <name>__*) into ly as <name>"""
    src = pya.Layout()
    src.read(os.path.join(HERE, "cells", fname))
    top = src.top_cell()
    for c in src.each_cell():
        if c.cell_index() != top.cell_index():
            c.name = f"{name}__{c.name}"
    dst = ly.create_cell(name)
    dst.copy_tree(top)
    fuse = pya.Region(dst.begin_shapes_rec(ly.layer(75, 0))).merged()
    mims = [p.bbox().to_dtype(ly.dbu) for p in fuse.each()]
    b = dst.dbbox()
    c_pf = sum((1.99 * m.width() * m.height() + 0.2383 * 2 * (m.width() + m.height())) / 1000 for m in mims)
    return {"bbox": [round(b.left, 3), round(b.bottom, 3), round(b.right, 3), round(b.top, 3)], "source": f"cells/{fname}",
            "info": f"supply tile {fname}: M5/M3 VDD, M4/M2/M1/SUB VSS" + (f", {len(mims)} MIM decaps" if mims else ""),
            "mim_decap_pF": round(c_pf, 4)}


def mim_tile(ly, c, w, l):
    """add bottom-plate tab + Via4 + Metal5 strap + leads + footprint marker to the flat MIM PCell in c"""
    box = lambda layer, x0, y0, x1, y1: c.shapes(ly.layer(*layer)).insert(pya.DBox(x0, y0, x1, y1))
    box(M4, TAB_M4, -MIM_ENC, 0, l + MIM_ENC)  # tab, merges with the PCell bottom plate
    n = int((l - 2 * 0.4 - VIA) / VIA_PITCH) + 1
    y0 = (l - (n - 1) * VIA_PITCH - VIA) / 2
    for vx in TAB_VIA_X:
        for i in range(n):
            box(V4, vx, y0 + i * VIA_PITCH, vx + VIA, y0 + i * VIA_PITCH + VIA)
    box(M5, TAB_STRAP[0], 0, TAB_STRAP[1], l)
    lw = min(LEAD_W, l - 1)
    yc0, yc1 = (l - lw) / 2, (l + lw) / 2
    x_w = TAB_M4 - MIM_HALO - LEAD_LEN
    x_e = w + MIM_ENC + MIM_HALO + LEAD_LEN
    box(M5, x_w, yc0, TAB_STRAP[0], yc1)  # bottom-plate lead -> west
    box(M5, w - 1.0, yc0, x_e, yc1)  # top-plate lead -> east (overlaps the plate, no off-grid sliver)
    fp = (x_w, -MIM_ENC - MIM_HALO, x_e, l + MIM_ENC + MIM_HALO)
    box(FP, *fp)
    r3 = lambda v: [round(x, 3) for x in v]
    return {"bbox": r3(fp), "top_plate": r3((0, 0, w, l)), "bottom_plate": r3((TAB_M4, -MIM_ENC, w + MIM_ENC, l + MIM_ENC)),
            "leads": {"bottom": r3((x_w, yc0, TAB_STRAP[0], yc1)), "top": r3((w, yc0, x_e, yc1))}, "vias_per_col": n}


def main():
    cells.gf180mcu()  # registers the "gf180mcu" library
    ly = pya.Layout()
    ly.dbu = 0.001
    devs = sch_devices()
    by_name = {p["name"]: (s, p) for s, p in devs}
    info = {}

    def add(name, pcell, params, text):
        pc = ly.create_cell(pcell, "gf180mcu", params)
        assert pc is not None and not pc.dbbox().empty(), f"PCell {pcell} {params} failed"
        c = ly.create_cell(name)
        c.insert(pya.CellInstArray(pc.cell_index(), pya.Trans()))
        c.flatten(True)
        b = c.dbbox()
        info[name] = {"bbox": [round(b.left, 3), round(b.bottom, 3), round(b.right, 3), round(b.top, 3)],
                      "params": params, "info": text}

    for sym, p in devs:
        if p.get("spice_ignore") == "true":
            continue
        name = p["name"]
        if sym in VOLT and name in ROWS:
            w, l, nf, m = um(p["W"]), um(p["L"]), int(p["nf"]), int(p["m"])
            rows = ROWS[name]
            assert m % rows == 0, f"{name}: m={m} not divisible into {rows} rows"
            dsym, dp = by_name[name + "D"]
            dum = int(dp["nf"]) * int(dp["m"]) // (2 * rows)  # dummy fingers per row end
            nf_row = m // rows * nf + 2 * dum
            add(f"{name}_row", "nfet", {"volt": VOLT[sym], "w_gate": w / nf, "l_gate": l, "nf": nf_row, "bulk": "None",
                                        "gate_con_pos": "top"},
                f"{name} {sym} W={w:g}/L={l:g} nf={nf} m={m}: {rows} row(s) x {m // rows} units "
                f"+ {dum} dummy fingers per row end ({name}D), Id {ID_MA[name]:g} mA")
            info[f"{name}_row"]["rows"] = rows
            info[f"{name}_row"].update(fet_tile(ly, ly.cell(f"{name}_row"), ID_MA[name] / rows))
        elif sym.startswith("ppolyf_u_1k"):
            w, l = um(p["W"]), um(p["L"])
            add(name, "ppolyf_u_high_Rs_resistor", {"volt": "5/6V" if "6p0" in sym else "3.3V", "w_res": w, "l_res": l},
                f"{name} {sym} W={w:g} L={l:g}")
        elif sym.startswith("cap_mim") and name == "CDCPL":
            continue  # supply decap, realised by the PG_MIM supply tiles
        elif sym.startswith("cap_mim"):
            w, l, m = um(p["W"]), um(p["L"]), int(p.get("m", 1))
            name = f"MIMC_{w:.4f}x{l:.4f}"
            add(name, "cap_mim", {"mim_option": "MIM-B", "metal_level": "M5", "wc": w, "lc": l},
                f"cap_mim_2f0_m4m5_noshield {w:g} x {l:g} + bottom-plate tab, leads, 1.2 um halo")
            info[name].update(mim_tile(ly, ly.cell(name), w, l))
    keep = set(info)
    for c in list(ly.each_cell()):  # drop the PCell variants, keep the flat device cells
        if c.name not in keep:
            ly.delete_cell(c.cell_index())
    for name, fname in PG_TILES.items():
        info[name] = import_tile(ly, name, fname)
    ly.write(os.path.join(HERE, "lna_core_devices.gds"))
    json.dump(info, open(os.path.join(HERE, "lna_core_devices.json"), "w"), indent=1)
    for n, d in info.items():
        b = d["bbox"]
        print(f"{n:22s} {b[2] - b[0]:8.2f} x {b[3] - b[1]:7.2f} um   {d['info']}")


main()
